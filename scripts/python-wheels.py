#!/usr/bin/env python3
"""Pin Python wheels for every system Neki supports, for buildPythonApplication.

Usage: scripts/python-wheels.py [--python 3.13] <name>==<version> ...

For each package, picks from PyPI the wheel that fits each system (the
package set's Python version; abi3 wheels count too, and pure-Python
`py3-none-any` wheels fit everywhere) and prints a .neki attribute set
`{ <system> = [ { url = …; sha256 = …; } … ]; … }` with PyPI's SHA-256
digests. List every dependency yourself: there is no resolver, the output
is the lock.
"""

import json
import re
import sys
import urllib.request

# The platform tags that fit each system, best first.
PLATFORMS = {
    "aarch64-darwin": [r"macosx_\d+_\d+_arm64", r"macosx_\d+_\d+_universal2"],
    "x86_64-darwin": [r"macosx_\d+_\d+_x86_64", r"macosx_\d+_\d+_universal2", r"macosx_\d+_\d+_intel"],
    "x86_64-linux": [r"manylinux\w*_x86_64"],
    "aarch64-linux": [r"manylinux\w*_aarch64"],
    "x86_64-windows": [r"win_amd64"],
}


def wheel_tags(filename):
    """(python tags, abi tag, platform tags) of a wheel file name."""
    parts = filename[: -len(".whl")].split("-")
    return parts[-3].split("."), parts[-2], parts[-1].split(".")


def score(filename, system, python):
    """How well a wheel fits (higher is better), or None if it doesn't."""
    pythons, abi, platforms = wheel_tags(filename)
    cp = "cp" + python.replace(".", "")
    minor = int(python.split(".")[1])
    if "any" in platforms and any(p in ("py3", "py2.py3") or p.startswith("py3") for p in pythons):
        return 1
    if cp in pythons and abi in (cp, "abi3"):
        python_score = 3
    elif abi == "abi3" and any(re.fullmatch(r"cp3(\d+)", p) and int(p[3:]) <= minor for p in pythons):
        python_score = 2
    else:
        return None
    for rank, pattern in enumerate(PLATFORMS[system]):
        if any(re.fullmatch(pattern, p) for p in platforms):
            # The oldest OS version is the most compatible: prefer it.
            versions = [int(n) for n in re.findall(r"\d+", ".".join(platforms))]
            return 100 * python_score - 10 * rank - min(versions, default=0) / 1000
    return None


def main():
    args = sys.argv[1:]
    python = "3.13"
    if args[:1] == ["--python"]:
        python, args = args[1], args[2:]
    if not args:
        sys.exit(__doc__)
    chosen = {system: [] for system in PLATFORMS}
    for spec in args:
        name, _, version = spec.partition("==")
        if not version:
            sys.exit(f"{spec}: give an exact version, like {spec}==1.0")
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        release = json.load(urllib.request.urlopen(url, timeout=60))
        wheels = [f for f in release["urls"] if f["packagetype"] == "bdist_wheel"]
        for system in PLATFORMS:
            scored = [(score(f["filename"], system, python), f) for f in wheels]
            scored = [(s, f) for s, f in scored if s is not None]
            if not scored:
                sys.exit(f"{name} {version} has no wheel for {system} and Python {python}")
            best = max(scored, key=lambda sf: sf[0])[1]
            chosen[system].append((best["url"], best["digests"]["sha256"]))
    print(f"# Generated by scripts/python-wheels.py --python {python} {' '.join(args)}")
    print("{")
    for system, wheels in chosen.items():
        print(f"  {system} = [")
        for url, sha in wheels:
            print(f'    {{ url = "{url}"; sha256 = "{sha}"; }}')
        print("  ];")
    print("}")


if __name__ == "__main__":
    main()
